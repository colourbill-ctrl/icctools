export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('profiletool.lang') || 'system')

  const setLang = useCallback((next) => {
    setLangState(next)
    localStorage.setItem('profiletool.lang', next)
  }, [])

  const resolved = lang === 'system' ? detectLang() : lang

  const t = useCallback((key, vars) => {
    const dict = I18N[resolved] || I18N.en
    let s = dict[key] ?? I18N.en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v))
    return s
  }, [resolved])

  useEffect(() => {
    document.documentElement.lang = resolved
  }, [resolved])

  const value = useMemo(() => ({ lang, setLang, resolved, t }), [lang, setLang, resolved, t])
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useLang() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error('useLang must be used inside <LangProvider>')
  return ctx
}

export function useT() {
  return useLang().t
}
